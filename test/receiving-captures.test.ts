import test from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadCapture, verifyCapture } from './helpers/capture.js';

/**
 * Captured inbound `UserMessage` requests (see docs/receiving-fixtures.md). Each
 * capture is verified through the real receiving path: bounded MIME parse, strict
 * XML, signature and coverage, signer validation against the captured trust
 * chain, session-key unwrap with the captured receiver credential, decryption,
 * payload-hash comparison and a full reference-set comparison. See
 * `test/helpers/capture.ts`.
 *
 * A capture may be `origin: "independent"` (recorded from a real peer) or
 * `origin: "local"` (generated by this project's sender). The ordinary suite
 * verifies whatever is present and skips when the directory holds no captures;
 * the Phase 6 validation command (`npm run validate:receive`) fails unless at
 * least two **independent** captures are present.
 */
const here = dirname(fileURLToPath(import.meta.url));
const fixtures = join(here, 'fixtures', 'inbound');

const names = existsSync(fixtures)
  ? readdirSync(fixtures, { withFileTypes: true })
      .filter((entry) => entry.isDirectory() && existsSync(join(fixtures, entry.name, 'metadata.json')))
      .map((entry) => entry.name)
      .sort()
  : [];

if (names.length === 0) {
  test('inbound wire captures (openAs4Message end to end)', (t) => {
    t.skip('no inbound captures recorded yet — see docs/receiving-fixtures.md');
  });
} else {
  for (const name of names) {
    test(`verifies the captured request ${name} end to end`, async () => {
      const capture = loadCapture(join(fixtures, name), name);
      assert.ok(
        capture.metadata.sender.implementation.length > 0,
        `${name}: metadata must name the sender implementation`,
      );
      const facts = await verifyCapture(capture);
      assert.equal(facts.name, name);
      assert.equal(facts.senderId, capture.metadata.senderParticipant.value);
      assert.equal(facts.receiverId, capture.metadata.receiverParticipant.value);
      assert.ok(facts.origin === 'independent' || facts.origin === 'local');
    });
  }

  test('every committed capture declares a distinct origin and a sender', () => {
    for (const name of names) {
      const capture = loadCapture(join(fixtures, name), name);
      assert.ok(capture.metadata.sender.version.length > 0, `${name}: metadata must name the sender version`);
      assert.ok(capture.metadata.capturedAt.length > 0, `${name}: metadata must record the capture time`);
      assert.ok(
        capture.metadata.receiverParticipant.value.length > 0,
        `${name}: metadata must record the receiver participant`,
      );
    }
  });
}
