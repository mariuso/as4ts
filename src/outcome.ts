/** The default classification rules. A caller may override any piece. */
export interface ClassifyTable {
  /** Per ebMS error code. A missing code is classified with `unknownEbmsCode`. */
  readonly ebms: Readonly<Record<string, OutcomeClass>>;
  /** Class when EBMS:0004 carries ErrorDetail `PEPPOL:NOT_SERVICED`. */
  readonly notServiced: OutcomeClass;
  /** Class when EBMS:0004 carries any other (or no) ErrorDetail. */
  readonly ebms0004Other: OutcomeClass;
  /** Class for an ebMS code not present in `ebms`. */
  readonly unknownEbmsCode: OutcomeClass;
  /** Class for each local `not-sent` reason. */
  readonly notSent: Readonly<Record<NotSentReason, OutcomeClass>>;
}

const ebmsClasses: Record<string, OutcomeClass> = {};
for (const [code, row] of Object.entries(EBMS_ERROR_TABLE)) ebmsClasses[code] = row.outcome;

export const DEFAULT_CLASSIFY_TABLE: ClassifyTable = {
  ebms: ebmsClasses,
  notServiced: 'fatal',
  ebms0004Other: 'retryable',
  unknownEbmsCode: 'fatal',
  notSent: {
    'message-id.invalid': 'fatal',
    'signer.unusable': 'fatal',
    'signature.mismatch': 'fatal',
    'certificate.refused': 'fatal',
    'certificate.unavailable': 'retryable',
    'spool.failed': 'retryable',
    aborted: 'retryable',
    'internal.error': 'unknown',
  },
};

/** Deeper class, used to pick the most severe when several errors are present. */
const RANK: Readonly<Record<OutcomeClass, number>> = { accepted: 0, retryable: 1, unknown: 2, fatal: 3 };

function moreSevere(a: OutcomeClass, b: OutcomeClass): OutcomeClass {
  return RANK[a] >= RANK[b] ? a : b;
}

export interface EbmsErrorInput {
  readonly code: string;
  /** ErrorDetail text; matters for EBMS:0004. */
  readonly detail?: string | null;
}

/** Classify one ebMS error. Unknown codes default to fatal (safe: do not retry). */
export function classifyEbmsError(err: EbmsErrorInput, table: ClassifyTable = DEFAULT_CLASSIFY_TABLE): OutcomeClass {
  if (err.code === 'EBMS:0004') {
    return err.detail === 'PEPPOL:NOT_SERVICED' ? table.notServiced : table.ebms0004Other;
  }
  return table.ebms[err.code] ?? table.unknownEbmsCode;
}

function classifyNoSignal(status: number): OutcomeClass {
  // 502/504 typically come from a gateway/load balancer in front of the
  // receiver's access point and can be returned after that access point already
  // took the message, so the send may have been delivered -> unknown.
  if (status === 502 || status === 504) return 'unknown';
  if (status >= 500) return 'retryable';
  if (status >= 400) return 'fatal';
  return 'unknown';
}

/**
 * Turn a factual {@link SendAs4Result} into the action a caller should take.
 * Pure: same result and table always give the same class. Never looks at hidden
 * state, never throws.
 */
export function classify(result: SendAs4Result, table: ClassifyTable = DEFAULT_CLASSIFY_TABLE): OutcomeClass {
  switch (result.outcome) {
    case 'receipt-verified':
      return 'accepted';
    case 'receipt-unverified':
      return 'unknown';
    case 'error-signal': {
      // An error that names a different message does not establish anything
      // about ours, so it must not stop delivery attempts.
      if (result.correlation === 'mismatched') return 'unknown';
      let worst: OutcomeClass = 'retryable';
      for (const error of result.errors) {
        worst = moreSevere(
          worst,
          classifyEbmsError({ code: error.code, ...(error.detail ? { detail: error.detail } : {}) }, table),
        );
      }
      return worst;
    }
    case 'no-signal':
      return classifyNoSignal(result.status);
    case 'transport-failure':
      // The request may have reached the receiver once the connection was
      // established (including an abort mid-upload or while waiting for the
      // receipt), so it is unknown. Only a failure known not to have sent
      // anything is safe to retry.
      return result.requestMayHaveBeenSent ? 'unknown' : 'retryable';
    case 'not-sent':
      return table.notSent[result.reason];
  }
}
